#!/bin/bash

# Проверка количества аргументов
if [ $# -ne 2 ]; then
    echo "Использование: $0 <начальный_номер> <конечный_номер>" >&2
    exit 1
fi

# Проверка, что аргументы - числа
if ! [[ $1 =~ ^[0-9]+$ ]] || ! [[ $2 =~ ^[0-9]+$ ]]; then
    echo "Ошибка: оба аргумента должны быть числами" >&2
    exit 1
fi

# Проверка, что начальный номер <= конечному
if [ "$1" -gt "$2" ]; then
    echo "Ошибка: начальный номер должен быть меньше или равен конечному" >&2
    exit 1
fi

start=$1
end=$2

# Создание файлов в диапазоне
for ((i=start; i<=end; i++)); do
    filename="step${i}.c"
    if [ ! -f "$filename" ]; then
        touch "$filename"
        echo "Создан файл: $filename"
    else
        echo "Файл $filename уже существует" >&2
    fi
done

echo "Готово! Создано файлов: $((end - start + 1)) в диапазоне от $start до $end."